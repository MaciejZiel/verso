#!/usr/bin/env python3
"""Write the Flathub manifest: the development one with Verso from a git tag.

The manifest in the repository root builds the working tree (type: dir). The
Flathub repository needs a source it can fetch, so this script copies the
manifest and replaces Verso's source with the release tag and its commit.

    tools/flathub_manifest.py v1.0.0
    # -> packaging/flathub/io.github.maciejziel.Verso.yml
"""

import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
APP_ID = "io.github.maciejziel.Verso"
URL = "https://github.com/MaciejZiel/verso.git"


def main(tag: str) -> int:
    commit = subprocess.run(
        ["git", "-C", str(ROOT), "rev-list", "-n", "1", tag],
        check=True, capture_output=True, text=True,
    ).stdout.strip()
    manifest = yaml.safe_load((ROOT / f"{APP_ID}.yml").read_text(encoding="utf-8"))
    (verso,) = [m for m in manifest["modules"] if isinstance(m, dict) and m.get("name") == "verso"]
    verso["sources"] = [{"type": "git", "url": URL, "tag": tag, "commit": commit}]
    out = ROOT / "packaging" / "flathub" / f"{APP_ID}.yml"
    header = (
        f"# Generated by tools/flathub_manifest.py {tag}; edit the manifest in the\n"
        "# repository root and run the script again.\n"
        "# --filesystem=home: a text editor opens files from anywhere and needs their\n"
        "# folders (relative images and links in the Markdown preview, links between\n"
        "# files, watching the open file for changes on disk).\n"
    )
    out.write_text(header + yaml.safe_dump(manifest, sort_keys=False, width=100), encoding="utf-8")
    print(f"{out.relative_to(ROOT)}: {tag} = {commit}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(f"usage: {sys.argv[0]} TAG")
    sys.exit(main(sys.argv[1]))
