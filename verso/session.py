"""Session and draft storage in ~/.local/share/verso (or $XDG_DATA_HOME/verso).

session.json lists the open documents; drafts/<id>.txt holds the text of documents with unsaved
changes, so nothing is lost when Verso is closed, crashes or the computer restarts."""

import json
import os
import tempfile
import uuid
from pathlib import Path

from gi.repository import GLib


def data_dir():
    return Path(GLib.get_user_data_dir()) / "verso"


def drafts_dir():
    path = data_dir() / "drafts"
    path.mkdir(parents=True, exist_ok=True)
    return path


def _atomic_write(path, text):
    """Write to a temporary file and rename it, so a crash never leaves half a file behind."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def new_draft_id():
    return uuid.uuid4().hex


def _draft_path(draft_id):
    # Ids are generated by us (hex), but never let a damaged session.json point outside the folder.
    if not draft_id or not all(c in "0123456789abcdef" for c in draft_id):
        raise ValueError(f"invalid draft id: {draft_id!r}")
    return drafts_dir() / f"{draft_id}.txt"


def write_draft(draft_id, text):
    _atomic_write(_draft_path(draft_id), text)


def read_draft(draft_id):
    try:
        return _draft_path(draft_id).read_text(encoding="utf-8")
    except (OSError, ValueError):
        return None


def delete_draft(draft_id):
    try:
        _draft_path(draft_id).unlink(missing_ok=True)
    except ValueError:
        pass


def save_session(documents, selected):
    """documents: list of dicts with uri, draft, encoding, newline (any of them may be None)."""
    _atomic_write(data_dir() / "session.json", json.dumps({"version": 1, "documents": documents, "selected": selected}, indent=1))


def load_session():
    try:
        data = json.loads((data_dir() / "session.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"documents": [], "selected": 0}
    documents = [d for d in data.get("documents", []) if isinstance(d, dict)]
    selected = data.get("selected", 0)
    return {"documents": documents, "selected": selected if isinstance(selected, int) else 0}


def prune_drafts(keep):
    """Remove draft files that no session entry refers to (left over from crashes or old sessions)."""
    for path in drafts_dir().glob("*.txt"):
        if path.stem not in keep:
            path.unlink(missing_ok=True)
